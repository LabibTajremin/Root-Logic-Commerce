// Regenerates src/themes/registry.gen.ts from the theme folders (spec §7.1).
// New theme = drop a folder with index.ts exporting `theme`, then run `pnpm themes:gen`.
import { readdirSync, statSync, writeFileSync } from 'node:fs'

const ids = readdirSync('src/themes')
  .filter((d) => !d.startsWith('_') && statSync(`src/themes/${d}`).isDirectory())
  .sort()
const loaders = ids
  .map((id) => `  '${id}': () => import('./${id}').then((m) => m.theme),`)
  .join('\n')
writeFileSync(
  'src/themes/registry.gen.ts',
  `// Generated by \`pnpm themes:gen\` — do not edit.
import type { Theme } from './_contract'

export const themeIds = [${ids.map((i) => `'${i}'`).join(', ')}] as const

// Dynamic imports: each route only loads the theme it renders.
export const themeLoaders: Record<string, () => Promise<Theme>> = {
${loaders}
}
`,
)
console.log(`themes: ${ids.join(', ')}`)
